/**
 * Return a Lucide icon as an inline SVG string.
 *
 * @param string $name   Icon name (see fashion_brand_theme_get_icon_paths).
 * @param array  $args {
 *     Optional. Icon attributes.
 *     @type int|string $width  Width in px. Default 24.
 *     @type int|string $height Height in px. Default 24.
 *     @type string     $class  Extra CSS class(es).
 * }
 * @return string
 */
function fashion_brand_theme_get_icon( $name, $args = array() ) {
	$paths = fashion_brand_theme_get_icon_paths( $name );

	if ( '' === $paths ) {
		return '';
	}

	$args = wp_parse_args(
		$args,
		array(
			'width'  => 24,
			'height' => 24,
			'class'  => '',
		)
	);

	$classes = trim( 'fbt-icon fbt-icon--' . sanitize_html_class( $name ) . ' ' . $args['class'] );

	return sprintf(
		'<svg class="%1$s" xmlns="http://www.w3.org/2000/svg" width="%2$s" height="%3$s" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">%4$s</svg>',
		esc_attr( $classes ),
		esc_attr( (string) $args['width'] ),
		esc_attr( (string) $args['height'] ),
		$paths // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- trusted SVG path markup from theme map.
	);
}

/**
 * Echo a Lucide icon.
 *
 * @param string $name Icon name.
 * @param array  $args Optional attributes.
 * @return void
 */
function fashion_brand_theme_icon( $name, $args = array() ) {
	echo fashion_brand_theme_get_icon( $name, $args ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- escaped in getter.
}
